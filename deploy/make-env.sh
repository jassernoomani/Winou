#!/usr/bin/env bash
# Writes .env for the demo server with fresh random secrets. Run once, from the repo root:
#
#   deploy/make-env.sh winou.duckdns.org you@example.com
#
# Never run it again on a server with data: a new LOCATION_FUZZ_SECRET moves every public
# position, and new database or storage passwords lock the services out of their own data.
set -euo pipefail

domain=${1:?usage: deploy/make-env.sh <domain> <admin email>}
admin=${2:?usage: deploy/make-env.sh <domain> <admin email>}

if [[ -e .env ]]; then
  echo ".env already exists; not overwriting it" >&2
  exit 1
fi

secret() { openssl rand -base64 48 | tr -d '/+=\n' | cut -c1-48; }

{
  sed -e '/^POSTGRES_PASSWORD=/d' -e '/^JWT_SECRET=/d' -e '/^S3_ACCESS_KEY=/d' -e '/^S3_SECRET_KEY=/d' \
      -e '/^LOCATION_FUZZ_SECRET=/d' -e '/^ADMIN_EMAILS=/d' .env.example
  echo
  echo "# --- Demo server (generated by deploy/make-env.sh) ---"
  echo "WINOU_DOMAIN=$domain"
  echo "ADMIN_EMAILS=$admin"
  echo "POSTGRES_PASSWORD=$(secret)"
  echo "JWT_SECRET=$(secret)"
  echo "S3_ACCESS_KEY=winou"
  echo "S3_SECRET_KEY=$(secret)"
  echo "LOCATION_FUZZ_SECRET=$(secret)"
} > .env
chmod 600 .env
echo "wrote .env for $domain (admin: $admin)"
